def is_valid_category(category: str) -> bool:
    """检查是否为有效的POI类别"""
    return category in POI_CATEGORIES


def get_category_desc(category: str) -> str:
    """获取POI类别描述"""
    return POI_CATEGORY_DESC.get(category, "")


def get_max_pool(category: str) -> int:
    """获取某类别的候选池数量上限"""
    return MAX_POOL.get(category, 10)


def get_travel_style(code: str) -> Dict[str, str]:
    """根据编码获取旅行风格"""
    for style in TRAVEL_STYLES:
        if style["code"] == code:
            return style
    return TRAVEL_STYLES[0]


def get_budget_level(code: str) -> Dict[str, str]:
    """根据编码获取预算档位"""
    for level in BUDGET_LEVELS:
        if level["code"] == code:
            return level
    return BUDGET_LEVELS[1]


def get_travel_mode(code: str) -> Dict[str, str]:
    """根据编码获取出行方式"""
    for mode in TRAVEL_MODES:
        if mode["code"] == code:
            return mode
    return TRAVEL_MODES[0]